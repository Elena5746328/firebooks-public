FIELDS = ("publisher", "year", "pages", "isbn", "cover_type", "description")
MISSING = {
    "", "-", "—", "не указан", "не указано",
    "описание пока не добавлено.", "уточняется",
}


def is_missing(value):
    return value is None or str(value).strip().casefold() in MISSING


def main():
    if not DB_PATH.is_file():
        raise SystemExit(
            f"База не найдена: {DB_PATH}\n"
            "Положите скрипт рядом с firebooks.db и запустите снова."
        )

    planned = []
    fix_author = False
    fix_author_12 = False

    # Сначала только читаем базу и определяем необходимые изменения.
    with sqlite3.connect(DB_PATH) as connection:
        connection.row_factory = sqlite3.Row
        columns = {
            row["name"] for row in connection.execute("PRAGMA table_info(books)")
        }
        if not set(FIELDS).issubset(columns):
            raise SystemExit("В таблице books отсутствуют необходимые поля.")

        for book_id, details in BOOK_DETAILS.items():
            old = connection.execute(
                "SELECT * FROM books WHERE id = ?", (book_id,)
            ).fetchone()
            if old is None:
                continue

            changes = {
                key: value
                for key, value in details.items()
                if key in FIELDS
                and not is_missing(value)
                and (
                    is_missing(old[key])
                    or (
                        key == "cover_type"
                        and book_id in (23, 24)
                        and str(old[key]).strip().casefold() == "комикс"
                    )
                )
            }
            if changes:
                planned.append((book_id, changes))

        author_row = connection.execute(
            "SELECT author FROM books WHERE id = 14"
        ).fetchone()
        fix_author = bool(author_row and author_row["author"] == "Софи Арни")
        author_row_12 = connection.execute(
            "SELECT author FROM books WHERE id = 12"
        ).fetchone()
        fix_author_12 = bool(
            author_row_12 and author_row_12["author"] == "Тори Майрен"
        )

    if not planned and not fix_author and not fix_author_12:
        print("Все доступные сведения уже заполнены. Изменений нет.")
        return

    # Резервная копия создаётся только если действительно есть изменения.
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    backup = DB_PATH.with_name(f"firebooks_backup_{stamp}.db")
    with sqlite3.connect(DB_PATH) as source:
        with sqlite3.connect(backup) as destination:
            source.backup(destination)

    with sqlite3.connect(DB_PATH) as connection:
        for book_id, changes in planned:
            assignments = ", ".join(f"{key} = ?" for key in changes)
            connection.execute(
                f"UPDATE books SET {assignments} WHERE id = ?",
                (*changes.values(), book_id),
            )

        if fix_author:
            connection.execute(
                "UPDATE books SET author = ? WHERE id = 14 AND author = ?",
                ("Софи Анри", "Софи Арни"),
            )
        if fix_author_12:
            connection.execute(
                "UPDATE books SET author = ? WHERE id = 12 AND author = ?",
                ("Тори Майрон", "Тори Майрен"),
            )
    print(
        f"Готово! Обновлено книг: {len(planned)}; "
        f"полей: {sum(len(changes) for _, changes in planned)}."
    )
    print(f"Резервная копия: {backup.name}")
    print("Цены, обложки, пользователи, корзина, заказы и отзывы не менялись.")


if __name__ == "__main__":
    main()
